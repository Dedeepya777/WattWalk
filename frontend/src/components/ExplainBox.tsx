/** Explanation box under a plan line (plan 11.3). The formula always comes from the plan. */
export function ExplainBox({
  formula,
  text,
  generatedBy,
  loading,
  error,
  onClose,
}: {
  formula: string;
  text: string | null;
  generatedBy: "template" | "llm" | null;
  loading: boolean;
  error: string | null;
  onClose: () => void;
}) {
  return (
    <div className="explain-box" role="region" aria-label="Explanation">
      <div className="explain-head">
        <strong>Why this number</strong>
        <button className="icon-button" onClick={onClose} aria-label="Close explanation">
          ×
        </button>
      </div>
      <p className="formula">{formula}</p>
      {loading ? (
        <p className="muted small">
          <span className="spinner" aria-hidden="true" /> Asking the planner to reword the
          template…
        </p>
      ) : error ? (
        <p className="inline-error">{error}</p>
      ) : text ? (
        <>
          <p className="explain-text">{text}</p>
          <p className="muted small">
            {generatedBy === "llm"
              ? "Reworded by the planner model; numbers unchanged."
              : "Generated by template."}
          </p>
        </>
      ) : null}
    </div>
  );
}
